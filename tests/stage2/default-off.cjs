'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html = fs.readFileSync(path.join(__dirname, '../../docs/index.html'), 'utf8');
const source = html.match(/const defaultData=\(\)=>\((\{[\s\S]*?\})\);/);
assert(source, 'UI defaults found');
assert.equal(vm.runInNewContext('(' + source[1] + ')').enableMultiplicitySolver, false);
assert(html.includes('p.enableMultiplicitySolver=false;'));
const snapshots = html.match(/planSnapshot:\{[^}]+/g);
assert.equal(snapshots.length, 2);
for (const snapshot of snapshots) assert(snapshot.includes('enableMultiplicitySolver:false'));
const normalized = html.match(/return \{parts,stocks,kerf,trim,[^\n]+/)[0];
assert(normalized.includes('enableMultiplicitySolver:false'));
const messages = html.match(/data:\{parts:data.parts[^}]+/g);
assert(messages.length >= 3);
for (const message of messages) assert(message.includes('enableMultiplicitySolver:false'));
console.log('Explicit OFF passed for UI, normalization, Worker messages and two snapshots.');
